#!/usr/bin/env python3
"""Generate standalone install.sh from auditable source files (stdlib only)."""
import base64, gzip, hashlib, io, tarfile, textwrap
from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=[root/'install.py',*sorted(p for p in (root/'src').rglob('*') if p.is_file() and '__pycache__' not in p.parts)]
buf=io.BytesIO()
with tarfile.open(fileobj=buf,mode='w') as archive:
    for path in files:
        data=path.read_bytes(); info=tarfile.TarInfo(path.relative_to(root).as_posix());info.size=len(data);info.mode=0o644;info.mtime=0;archive.addfile(info,io.BytesIO(data))
raw=gzip.compress(buf.getvalue(),mtime=0)
encoded='\n'.join(textwrap.wrap(base64.b64encode(raw).decode(),76))
header='''#!/bin/bash
# PVE Hardware Monitor v0.1.7 — standalone, generated by scripts/build-installer.py
# The embedded archive is generated from install.py and src/. No network calls.
set -euo pipefail
umask 077
if [[ ${1:-} == --version ]]; then echo 'PVE Hardware Monitor v0.1.7'; exit 0; fi
if [[ $# -gt 1 ]]; then echo 'Usage: install.sh [check|install|repair|status|uninstall|activate]' >&2; exit 2; fi
for cmd in python3 base64 sha256sum tar mktemp; do command -v "$cmd" >/dev/null || { echo "Missing dependency: $cmd" >&2; exit 1; }; done
work=$(mktemp -d)
trap 'rm -rf -- "$work"' EXIT
base64 -d > "$work/payload.tar.gz" <<'PHM_PAYLOAD'
'''
footer=f'''PHM_PAYLOAD
printf '%s  %s\\n' '{hashlib.sha256(raw).hexdigest()}' "$work/payload.tar.gz" | sha256sum -c --status
mkdir "$work/source"
tar -xzf "$work/payload.tar.gz" -C "$work/source" --no-same-owner --no-same-permissions
python3 "$work/source/install.py" "${{1:-install}}"
'''
p=root/'install.sh';p.write_text(header+encoded+'\n'+footer);p.chmod(0o755)
